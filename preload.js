const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  pickPdfs: (kind) => ipcRenderer.invoke('pdf:pick', kind),
  registerPdf: (filePath) => ipcRenderer.invoke('pdf:register', filePath),
  readPdfRange: (id, begin, end) => ipcRenderer.invoke('pdf:read', id, begin, end),
  statPdf: (id) => ipcRenderer.invoke('pdf:stat', id),
  closePdf: (id) => ipcRenderer.invoke('pdf:close', id),
  openPathsEverywhere: () => ipcRenderer.invoke('pdf:openPaths'),
  pathForDroppedFile: (file) => webUtils.getPathForFile(file),
  onOpenFiles: (callback) => ipcRenderer.on('pdf:open', (_event, paths) => callback(paths)),
  rendererReady: () => ipcRenderer.send('renderer:ready'),
  placeFiles: (paths) => ipcRenderer.invoke('pdf:place', paths),
  setOpenTabs: (paths) => ipcRenderer.send('window:tabs', paths),
  requestCloseWindow: () => ipcRenderer.send('window:requestClose'),
  openIn: () => ipcRenderer.invoke('settings:openIn'),
  setOpenIn: (mode) => ipcRenderer.invoke('settings:setOpenIn', mode),
  onOpenInChanged: (callback) => ipcRenderer.on('settings:openInChanged', (_event, mode) => callback(mode)),
  twoPage: () => ipcRenderer.invoke('settings:twoPage'),
  setTwoPage: (on) => ipcRenderer.invoke('settings:setTwoPage', on),
  onTwoPageChanged: (callback) => ipcRenderer.on('settings:twoPageChanged', (_event, on) => callback(on)),
  recentFiles: () => ipcRenderer.invoke('recent:list'),
  noteRecent: (filePath) => ipcRenderer.send('recent:opened', filePath),
  rememberPage: (filePath, page) => ipcRenderer.send('recent:page', filePath, page),
  rememberedPage: (filePath) => ipcRenderer.invoke('recent:pageOf', filePath),
  openRecent: (filePath) => ipcRenderer.invoke('recent:open', filePath),
  clearRecent: () => ipcRenderer.invoke('recent:clear'),
  hasPdfgear: () => ipcRenderer.invoke('pdfgear:available'),
  openInPdfgear: (id) => ipcRenderer.invoke('pdfgear:open', id),
  printOptions: () => ipcRenderer.invoke('print:options'),
  savePrintSetup: (setup) => ipcRenderer.invoke('print:saveSetup', setup),
  deletePrintSetup: (name) => ipcRenderer.invoke('print:deleteSetup', name),
  print: (request) => ipcRenderer.invoke('print:run', request),
  saveAs: (id, rotation) => ipcRenderer.invoke('pdf:saveAs', id, rotation),
  merge: (entries, options) => ipcRenderer.invoke('pages:merge', entries, options),
  inspectImage: (filePath) => ipcRenderer.invoke('image:inspect', filePath),
  readImage: (filePath) => ipcRenderer.invoke('image:read', filePath),
  split: (request) => ipcRenderer.invoke('pages:split', request),
  onSplitProgress: (callback) => ipcRenderer.on('pages:progress', (_event, done, total) => callback(done, total)),
  pickFolder: (current) => ipcRenderer.invoke('pages:pickFolder', current),
  openOutputFolder: () => ipcRenderer.invoke('pages:openFolder'),
  organize: (request) => ipcRenderer.invoke('pages:organize', request),
  setUnsaved: (unsaved) => ipcRenderer.send('window:unsaved', unsaved),
  onCloseRequested: (callback) => ipcRenderer.on('window:closeRequested', () => callback()),
  closeWindow: () => ipcRenderer.send('window:close'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  checkForUpdate: () => ipcRenderer.invoke('update:check'),
  downloadUpdate: () => ipcRenderer.invoke('update:download'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateProgress: (callback) => ipcRenderer.on('update:progress', (_event, percent) => callback(percent)),
  openDefaultApps: () => ipcRenderer.invoke('app:openDefaultApps'),
});
